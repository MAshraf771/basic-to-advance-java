
 class Escape {
  public static void main(String[] args) {
    System.out.println("my name is \"m ashraf\"");
    System.out.println("my name is \\m ashraf\\");
    System.out.println("my name is \tm ashraf");
    System.out.println("my name is \bm ashraf");
    System.out.println("my name is \nm ashraf");
  }
  
}
